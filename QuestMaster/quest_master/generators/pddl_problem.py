from ..models.quest_data import EnhancedQuestData


class PDDLProblemGenerator:
    def __init__(self, quest_data: EnhancedQuestData):
        self.quest = quest_data
        self.problem_name = "quest-problem"

    def _name(self, obj_id: str) -> str:
        """Player-facing name on a single line (a newline would end the PDDL comment it goes in)."""
        return " ".join(self.quest.display_names.get(obj_id, obj_id).split())

    def _named(self, obj_id: str, declaration: str) -> str:
        """Append the player-facing name as a comment, so the PDDL reads like the story."""
        return f"{declaration}  ; {self._name(obj_id)}" if obj_id in self.quest.display_names else declaration

    def generate(self) -> str:
        """Generate the problem file for the quest domain."""
        q = self.quest
        destination = q.goal_conditions[0].split()[-1]
        objects = ["hero - agent"]
        objects += [self._named(loc, f"{loc} - location") for loc in q.locations]
        objects += [self._named(item, f"{item} - item") for item in q.items]
        objects += [self._named(o, f"{o} - obstacle") for o in dict.fromkeys(q.obstacles.values())]

        init = [";; the hero sets out", f"(at hero {q.initial_location})", "(= (total-cost) 0)",
                ";; places that can be entered freely (guarded ones open once their guardian falls)"]
        # A location is enterable unless an obstacle guards it; defeating the obstacle clears it.
        init += [f"(clear {loc})" for loc in q.locations if loc not in q.obstacles]
        init += [";; the roads of the realm"]
        for loc1, loc2 in q.connections:
            init += [f"(connected {loc1} {loc2})", f"(connected {loc2} {loc1})"]
        init += [";; hidden treasures"]
        init += [f"(item_at {item} {loc})" for item, loc in q.item_locations.items()]
        init += [";; guardians and their weaknesses"]
        init += [f"(guarded_by {loc} {obstacle})" for loc, obstacle in q.obstacles.items()]
        init += [f"(defeats {item} {obstacle})" for item, obstacle in q.defeats.items()]

        lines = [
            f";; The Quest for {self._name(destination)} - generated by QuestMaster",
            f"(define (problem {self.problem_name})",
            "  (:domain quest-domain)",
            "  (:objects",
            *(f"    {obj}" for obj in objects),
            "  )",
            "  (:init",
            *(f"    {fact}" for fact in init),
            "  )",
            "  (:goal (and",
            *(f"    ({condition})" for condition in q.goal_conditions),
            "  ))",
            "  (:metric minimize (total-cost))",
            ")",
        ]
        return "\n".join(lines)
